        public static bool Apply(ulong applicationId, string buildId, byte[] program)
        {
            if (applicationId != TitleId)
            {
                return false;
            }

            foreach ((string id, int offset) in _builds)
            {
                if (id != buildId)
                {
                    continue;
                }

                if (program.Length < offset + _nextendoModulus.Length ||
                    !program.AsSpan(offset, _eaModulusPrefix.Length).SequenceEqual(_eaModulusPrefix))
                {
                    Logger.Error?.Print(LogClass.ModLoader, "[Nextendo] PvZ BfN: CA entry not found, trust patch skipped");

                    return false;
                }

                _nextendoModulus.CopyTo(program, offset);

                Logger.Info?.Print(LogClass.ModLoader, "[Nextendo] PvZ BfN: built-in CA trust patch applied");

                return true;
            }

            return false;
        }
    }
